	<?php if ( $pegel_uuid ) : ?>
		<div style="margin:2rem 0;">
			<h2>Aktueller Pegelstand</h2>
			<?php echo do_shortcode( '[pegel_station uuid="' . esc_attr( $pegel_uuid ) . '" name="' . esc_attr( get_the_title() ) . '"]' ); ?>
		</div>
	<?php endif; ?>

