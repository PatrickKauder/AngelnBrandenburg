	<?php if ( has_post_thumbnail() ) : ?>
		<div class="abb-img-wrap abb-img-wrap--16-9" style="border-radius:1rem;overflow:hidden;margin-bottom:2rem;max-height:450px;">
			<?php the_post_thumbnail( 'abb-hero', [
