				'decoding'=> 'async',
				'class'   => 'abb-hero-img',
				'alt'     => esc_attr( get_the_title() . ' – Angelgewässer Brandenburg' ),
			] ); ?>
		</div>
	<?php endif; ?>

	<!-- Main Content -->
	<div class="abb-gewaesser-content entry-content" style="max-width:800px;">
		<?php the_content(); ?>
	</div>

